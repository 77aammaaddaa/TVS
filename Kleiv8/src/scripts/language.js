export function getLanguage() {
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (saved === 'ar' || saved === 'en') return saved;
  } catch {}
  return document.documentElement.lang === 'ar' ? 'ar' : 'en';
}

export function setLanguage(lang) {
  const next = lang === 'ar' ? 'ar' : 'en';
  try { localStorage.setItem(LANGUAGE_STORAGE_KEY, next); } catch {}
  applyLanguage(next);
  window.dispatchEvent(new CustomEvent(LANGUAGE_UPDATED_EVENT, { detail: { lang: next } }));
}

export function t(key, lang = getLanguage()) {
  return translations[lang]?.[key] ?? translations.en[key] ?? key;
}

export function applyLanguage(lang = getLanguage()) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.body.dataset.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (key) element.textContent = t(key, lang);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (key) element.placeholder = t(key, lang);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
    const key = element.dataset.i18nAria;
    if (key) element.setAttribute('aria-label', t(key, lang));
  });
}

export function itemName(item, lang = getLanguage()) {
  return lang === 'ar' ? (item.name_ar || item.name_en) : item.name_en;
}

export function itemDescription(item, lang = getLanguage()) {
  return lang === 'ar' ? (item.description_ar || item.description || '') : (item.description || item.description_ar || '');
}

export function categoryName(category, lang = getLanguage()) {
  if (lang !== 'ar') return category;
  const names = { Coffee: 'قهوة ساخنة', Matcha: 'ماتشا', 'Cold drinks': 'مشروبات باردة', Bakery: 'مخبوزات', Desserts: 'حلويات', Menu: 'القائمة' };
  return names[category] ?? category;
}
