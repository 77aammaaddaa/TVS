const reportedCopyIssues = new Set();
const arabicScriptPattern = /[\u0600-\u06ff\u0750-\u077f\u08a0-\u08ff]/u;
const latinScriptPattern = /[A-Za-z]/u;

export function getLanguage() {
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (saved === 'ar' || saved === 'en') return saved;
  } catch {}
  return document.documentElement.lang === 'ar' ? 'ar' : 'en';
}

export function setLanguage(lang) {
  const next = lang === 'ar' ? 'ar' : 'en';
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, next);
  } catch {}
  applyLanguage(next);
  window.dispatchEvent(new CustomEvent(LANGUAGE_UPDATED_EVENT, { detail: { lang: next } }));
}

export function t(key, lang = getLanguage()) {
  const value = translations[lang]?.[key];
  if (value !== undefined) return value;
  console.error(`Missing ${lang} translation for "${key}".`);
  return lang === 'ar' ? 'نص غير متوفر' : 'Text unavailable';
}

function isLanguageSafe(value, lang) {
  return lang === 'ar'
    ? !latinScriptPattern.test(value)
    : !arabicScriptPattern.test(value);
}

function safeMenuText(value, lang, fallback, item, field) {
  const text = typeof value === 'string' ? value.trim() : '';
  if (!text) return fallback;
  if (isLanguageSafe(text, lang)) return text;

  const issueKey = `${item?.id ?? 'menu'}:${field}:${lang}`;
  if (!reportedCopyIssues.has(issueKey)) {
    reportedCopyIssues.add(issueKey);
    console.warn(`Menu item "${item?.id ?? 'unknown'}" has ${field} copy in the wrong language.`);
  }
  return fallback;
}

export function itemName(item, lang = getLanguage()) {
  const value = lang === 'ar' ? item?.name_ar : (item?.name_en ?? item?.name);
  return safeMenuText(value, lang, t('untranslatedItem', lang), item, lang === 'ar' ? 'name_ar' : 'name_en');
}

export function itemDescription(item, lang = getLanguage()) {
  const value = lang === 'ar' ? item?.description_ar : (item?.description_en ?? item?.description);
  return safeMenuText(value, lang, '', item, lang === 'ar' ? 'description_ar' : 'description_en');
}

export function categoryName(category, lang = getLanguage()) {
  const categoryEn = typeof category === 'string'
    ? category
    : (category?.category_en ?? category?.category ?? '');
  const categoryAr = typeof category === 'object' && category
    ? (category.category_ar ?? '')
    : '';
  const candidates = [categoryEn, categoryAr].map((value) => String(value).trim().toLocaleLowerCase());
  const definition = categoryDefinitions.find((entry) =>
    entry.values.some((value) => candidates.includes(value))
  );
  if (definition) return t(definition.key, lang);

  const source = lang === 'ar' ? categoryAr : categoryEn;
  return safeMenuText(source, lang, t('otherCategory', lang), category, 'category');
}

export function badgeName(item, lang = getLanguage()) {
  const source = lang === 'ar'
    ? (item?.badge_ar ?? '')
    : (item?.badge_en ?? item?.badge ?? '');
  if (!source) return '';

  const text = String(source).trim();
  const knownBadge = badgeDefinitions.find((badge) =>
    badge.en.toLocaleLowerCase() === text.toLocaleLowerCase() ||
    badge.ar === text
  );
  if (knownBadge) return lang === 'ar' ? knownBadge.ar : knownBadge.en;
  return safeMenuText(text, lang, '', item, lang === 'ar' ? 'badge_ar' : 'badge_en');
}

export function formatNumber(value, lang = getLanguage()) {
  return new Intl.NumberFormat(lang === 'ar' ? 'ar-EG' : 'en-EG', {
    maximumFractionDigits: 2,
  }).format(value);
}

export function formatPrice(value, lang = getLanguage()) {
  const currency = lang === 'ar' ? 'جنيه مصري' : 'EGP';
  return `${formatNumber(value, lang)} ${currency}`;
}

export function applyLanguage(lang = getLanguage()) {
  const next = lang === 'ar' ? 'ar' : 'en';
  const documentElement = document.documentElement;
  documentElement.lang = next;
  documentElement.dir = next === 'ar' ? 'rtl' : 'ltr';
  document.body.dataset.lang = next;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (key) element.textContent = t(key, next);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (key && 'placeholder' in element) element.placeholder = t(key, next);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
    const key = element.dataset.i18nAria;
    if (key) element.setAttribute('aria-label', t(key, next));
  });
  document.querySelectorAll('[data-i18n-title]').forEach((element) => {
    const key = element.dataset.i18nTitle;
    if (key) element.setAttribute('title', t(key, next));
  });
  document.querySelectorAll('img[data-i18n-src-en][data-i18n-src-ar]').forEach((element) => {
    const source = next === 'ar' ? element.dataset.i18nSrcAr : element.dataset.i18nSrcEn;
    if (source !== undefined) element.setAttribute('src', source);
  });

  const title = document.querySelector('title[data-i18n-title-en]');
  if (title) {
    document.title = next === 'ar'
      ? title.dataset.i18nTitleAr ?? t('pageTitle', next)
      : title.dataset.i18nTitleEn ?? t('pageTitle', next);
  }
  document.querySelectorAll('meta[data-i18n-content-en][data-i18n-content-ar]').forEach((element) => {
    const content = next === 'ar' ? element.dataset.i18nContentAr : element.dataset.i18nContentEn;
    if (content !== undefined) element.setAttribute('content', content);
  });

  documentElement.classList.remove('locale-pending');
}
